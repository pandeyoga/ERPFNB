#!/usr/bin/env python3
"""Generate frontend/src/lib/routePerms.generated.js from the route guards in the portal shells.

Every portal shell guards its routes with `g(need, <Page/>)` (lib/portalGate.js). The sidebar must show a menu item
ONLY when the user passes that same guard — otherwise the item leads to /no-access ("menu jebakan", found by
scripts/ui_metrics/roles.js). Instead of copying permissions into lib/navigationSchema by hand (they drift), this
script extracts them from the route definitions, so the guard stays the single source of truth.

usage: python3 scripts/gen_route_perms.py          # write the file
       python3 scripts/gen_route_perms.py --check  # exit 1 if the file is stale (used by audit_ui_ia.py)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "frontend" / "src"
OUT = SRC / "lib" / "routePerms.generated.js"

# portal shell → URL prefix it is mounted on (App.js: <Route path="/finance/*" …>)
PORTALS = {
    "portals/admin/AdminPortal.jsx": "/admin",
    "portals/executive/ExecutivePortal.jsx": "/executive",
    "portals/finance/FinancePortal.jsx": "/finance",
    "portals/procurement/ProcurementPortal.jsx": "/procurement",
    "portals/outlet/OutletPortal.jsx": "/outlet",
    "portals/inventory/InventoryPortal.jsx": "/inventory",
    "portals/owner/OwnerPortal.jsx": "/owner",
    "portals/HRPortal.jsx": "/hr",
}

ROUTE_RE = re.compile(
    r'<Route\s+(?:path="(?P<path>[^"]*)"|(?P<index>index))\s+element=\{\s*g\(\s*(?P<need>"[^"]*"|\[[^\]]*\])',
    re.S,
)


def extract() -> dict:
    perms: dict = {}
    for rel, base in PORTALS.items():
        text = (SRC / rel).read_text()
        for m in ROUTE_RE.finditer(text):
            sub = "" if m.group("index") else m.group("path")
            need = json.loads(m.group("need").replace("'", '"'))
            needs = [need] if isinstance(need, str) else need
            url = base + ("/" + sub if sub else "")
            perms[url] = sorted(set(perms.get(url, [])) | set(needs))
    return dict(sorted(perms.items()))


def render(perms: dict) -> str:
    body = json.dumps(perms, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by scripts/gen_route_perms.py — do not edit by hand.\n"
        "// Route → permissions of its guard g(need, …) in the portal shell (any-of). Used by lib/unifiedNav.js so a\n"
        "// menu item is visible only when its route guard would let the user in.\n"
        f"export const ROUTE_PERMS = {body};\n"
    )


def main() -> int:
    content = render(extract())
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != content:
            print(f"STALE: {OUT.relative_to(ROOT)} — run python3 scripts/gen_route_perms.py")
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} up to date ({content.count(': [')} routes)")
        return 0
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)} ({content.count(': [')} routes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
